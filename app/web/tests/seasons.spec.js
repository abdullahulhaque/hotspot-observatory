import { test, expect } from '@playwright/test';
import { openTab, openView } from './helpers.js';
const fmt = value => new Intl.NumberFormat('en-US', {maximumFractionDigits:1}).format(value);

test('view and analysis tabs update the address and survive a reload', async ({page}) => {
  await page.setViewportSize({width:1024,height:1100});
  await page.goto('/');
  const current = page.getByRole('tablist',{name:'Views'}).locator('[aria-selected=true]');
  await expect(current).toHaveText('Explore');
  await openView(page, 'Methods');
  await expect(page).toHaveURL(/view=methods/);
  await expect(page.getByRole('heading',{level:1})).toHaveText('How the two records are put on one scale');
  await page.reload();
  await expect(current).toHaveText('Methods');
  await openView(page, 'Explore');
  await openTab(page, 'Seasons');
  await page.reload();
  await expect(page.getByRole('tablist',{name:'Analyses'}).locator('[aria-selected=true]')).toHaveText('Seasons');
  await expect(page.locator('.season-panel')).toBeVisible();
});

test('Gran Chaco: ten complete springs, actual harmonized totals, partial October and regional updates', async ({page,request}) => {
  const payload = await (await request.get('/api/series?bbox=-64,-28,-59,-24&start=2003-01&end=2026-10&daynight=D')).json();
  expect(payload.synthetic).toBe(false);
  // Independent summation, not the frontend aggregation helper.
  const totals = Array.from({length:10},(_,i)=>2016+i).map(year => payload.data.filter(r=>r.year===year && [9,10,11].includes(r.month)).reduce((sum,r)=>sum+r.harmonized,0));
  const sorted=[...totals].sort((a,b)=>a-b), median=(sorted[4]+sorted[5])/2;
  await page.goto('/');
  await page.getByRole('button',{name:'Gran Chaco',exact:true}).click();
  await openTab(page, 'Seasons');
  await expect(page.locator('.season-panel')).toHaveAttribute('aria-busy','false');
  await expect(page.getByLabel('Season',{exact:true})).toHaveValue('spring');
  await expect(page.getByLabel('Comparison window')).toHaveValue('10');
  await expect(page.locator('.season-bar.complete')).toHaveCount(10);
  await expect(page.locator('.season-bar.incomplete')).toHaveCount(1);
  for (let index=0;index<10;index++) await expect(page.locator(`[data-season="spring-${2016+index}"]`)).toHaveAttribute('data-total',String(totals[index]));
  await expect(page.locator('.season-median')).toHaveAttribute('data-value',String(median));
  await expect(page.locator('.season-comparison')).toContainText(`below the displayed complete-season median of ${fmt(median)}`);
  await expect(page.locator('.season-detail h3')).toHaveText('Spring 2025');
  const partial = payload.data.filter(r=>r.year===2026 && [9,10].includes(r.month)).reduce((sum,r)=>sum+r.harmonized,0);
  const latest = page.locator('[data-season="spring-2026"]');
  await expect(latest).toHaveAttribute('data-total','');
  await expect(latest).toHaveAttribute('data-partial-total',String(partial));
  await latest.hover();
  await expect(page.locator('.season-detail-heading')).toContainText(`Incomplete · partial total: ${fmt(partial)}`);
  await expect(page.locator('.season-detail')).toContainText('2026-11');
  await expect(page.locator('.season-detail')).toContainText('Unavailable');
  await expect(page.locator('.season-detail')).toContainText('NRT · provisional');
  await expect(page.locator('.season-comparison')).toContainText('comparison withheld');
  await expect(page.locator('.season-median')).toHaveAttribute('data-value',String(median));
  await page.locator('.season-panel').screenshot({path:'test-results/seasons-desktop.png'});
  await page.getByLabel('Comparison window').selectOption('3');
  await expect(page.locator('.season-bar.complete')).toHaveCount(3);
  await page.getByLabel('Comparison window').selectOption('5');
  await expect(page.locator('.season-bar.complete')).toHaveCount(5);
  await page.getByRole('button',{name:'Pampas',exact:true}).click();
  await expect(page.locator('.season-panel')).toHaveAttribute('aria-busy','false');
  const pampas=await (await request.get('/api/series?bbox=-64,-38,-59,-33&start=2025-09&end=2025-11&daynight=D')).json();
  await expect(page.locator('[data-season="spring-2025"]')).toHaveAttribute('data-total',String(pampas.data.reduce((sum,r)=>sum+r.harmonized,0)));
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.locator('.season-panel').screenshot({path:'test-results/seasons-mobile.png'});
  await openTab(page, 'Calendar');
  await expect(page.locator('.calendar')).toBeVisible();
  await expect(page.locator('.anomaly-panel')).toBeVisible();
  await expect(page.locator('.study-area-name')).toHaveText('Pampas');
});

test('summer boundaries and incomplete winter coverage preserve source flags and night filtering', async ({page}) => {
  await page.goto('/');
  await openTab(page, 'Seasons');
  await page.getByLabel('Season',{exact:true}).selectOption('summer');
  const summer=page.locator('[data-season="summer-2025"]');
  await summer.focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('.season-detail h3')).toHaveText('Summer 2025–26');
  await expect(page.locator('.season-detail tbody th')).toHaveText(['2025-12','2026-01','2026-02']);
  await expect(page.locator('[data-season="summer-2026"]')).toHaveCount(0);
  await page.getByLabel('Season',{exact:true}).selectOption('winter');
  await page.locator('[data-season="winter-2026"]').click();
  await expect(page.locator('.season-detail')).toContainText('Gap-filled estimate');
  await expect(page.locator('.season-detail')).toContainText('Incomplete observations');
  await expect(page.locator('.season-detail')).toContainText('confirmed missing S-NPP days');
  await expect(page.locator('.season-comparison')).toContainText('comparison withheld');
  await page.getByLabel('Season day or night').selectOption('N');
  await expect(page.locator('.season-panel')).toHaveAttribute('aria-busy','false');
  await expect(page.locator('.season-detail')).not.toContainText('Gap-filled estimate');
  await expect(page.locator('.season-detail')).toContainText('Observed · Incomplete observations');
});
