import { test, expect } from '@playwright/test';

test('Argentina data, comparison, flags, validation and CSV stay connected', async ({ page, request }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const meta = await (await request.get('/api/meta')).json();
  await page.goto('/');
  await expect(page.getByLabel('Start month')).toHaveValue('2003-01');
  await expect(page.getByLabel('End month')).toHaveValue(meta.end);
  await expect(page.locator('.synthetic-banner')).toHaveCount(meta.synthetic ? 1 : 0);
  await expect(page.getByRole('heading', { name: 'Sensor comparison' })).toBeVisible();
  await expect(page.locator('.summary strong')).not.toHaveText('0');
  await expect(page.locator('.interval-band').first()).toBeVisible();
  await expect(page.locator('.viirs-marker')).toContainText('VIIRS record begins');
  await expect(page.getByRole('button', { name: /Jan 2003:/ })).toHaveClass(/backcast/);
  const gapfill = page.getByRole('button', { name: /Jan 2012:/ });
  await expect(gapfill).toHaveClass(/gapfill/);
  await expect(gapfill.locator('.source-symbol')).toHaveText('◆');
  await expect(gapfill.locator('.gap-symbol')).toHaveText('△');
  const flaggedBackcast = page.getByRole('button', { name: /Jun 2005:/ });
  await expect(flaggedBackcast.locator('.source-symbol')).toHaveText('•');
  await expect(flaggedBackcast.locator('.gap-symbol')).toHaveText('△');
  const flaggedObserved = page.getByRole('button', { name: /May 2014:/ });
  await expect(flaggedObserved.locator('.source-symbol')).toBeEmpty();
  await expect(flaggedObserved.locator('.gap-symbol')).toHaveText('△');
  await expect(page.locator('.chart-backcast')).toHaveCount(108);
  await expect(page.locator('.chart-gapfill')).toHaveCount(4);
  await expect(page.locator('.chart-gap-flag')).toHaveCount(10);
  await expect(page.locator('.gapfill-band')).toHaveCount(3);
  await expect(page.locator('rect.gapfill-band').first()).toHaveAttribute('width', '6');
  await gapfill.click();
  await expect(page.locator('.chart-values')).toContainText('◆ Gap-filled month');
  await expect(page.locator('.chart-values')).toContainText('80% interval');
  await expect(page.getByRole('heading', { name: 'Method and validation' })).toBeVisible();
  await expect(page.locator('.legend')).toContainText('active cell-days');
  await page.screenshot({ path: 'test-results/argentina-desktop.png', fullPage: true });
  for (const name of ['Gran Chaco', 'Pampas', 'Patagonia']) {
    await page.getByRole('button', { name, exact: true }).click();
    await expect(page.locator('.calendar-scroll')).toHaveAttribute('aria-busy', 'false');
    await expect(page.locator('.summary strong')).not.toHaveText(/^(0|—|No data in this area)$/);
  }
  await page.getByRole('button', { name: /Aug 2024:/ }).click();
  await expect(page.locator('.month-pill')).toHaveText('2024-08');
  await expect(page.locator('.anomaly-number')).not.toHaveText('—');
  await page.getByLabel('Inspect chart month').focus();
  await page.keyboard.press('Home');
  await expect(page.locator('.month-pill')).toHaveText('2003-01');
  await page.getByRole('button', { name: 'Harmonized', exact: true }).click();
  await expect(page.getByRole('button', { name: /Jan 2003:/ })).not.toHaveClass(/missing/);
  await page.getByLabel('Day or night').selectOption('N');
  await expect(page.locator('.calendar-panel .info')).toContainText('Nighttime harmonized is unavailable before 2012');
  await expect(page.getByRole('button', { name: /Jan 2003: unavailable/ })).toHaveClass(/missing/);
  await expect(page.getByRole('button', { name: /Jan 2012:/ })).not.toHaveClass(/missing/);
  await expect(page.locator('.chart-gapfill, .chart-backcast')).toHaveCount(0);
  await expect(page.locator('.chart-gap-flag')).toHaveCount(10);
  await expect(page.getByRole('button', { name: /Jan 2012:/ }).locator('.source-symbol')).toBeEmpty();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: /Download CSV/ }).click();
  expect((await downloadPromise).suggestedFilename()).toContain('hotspots-2003-01');
  await page.getByLabel('West longitude').fill('0');
  await page.getByLabel('East longitude').fill('1');
  await page.getByLabel('South latitude').fill('0');
  await page.getByLabel('North latitude').fill('1');
  await page.getByRole('button', { name: /Apply coordinates/ }).click();
  await expect(page.locator('.calendar-scroll')).toContainText('No data in this area');
  await expect(page.locator('.sensor-panel')).toContainText('No data in this area');
  await expect(page.locator('.calendar .cell')).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('rectangle changes coordinates and mobile layout fits', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('button', { name: /Aug 2024:/ })).toBeVisible();
  const canvas = page.locator('.maplibregl-canvas');
  await expect(canvas).toBeVisible();
  const previous = await page.getByLabel('West longitude').inputValue();
  await page.getByRole('button', { name: /Draw a rectangle/ }).click();
  const rect = await canvas.boundingBox();
  await page.mouse.move(rect.x + rect.width * 0.3, rect.y + rect.height * 0.35);
  await page.mouse.down();
  await page.mouse.move(rect.x + rect.width * 0.7, rect.y + rect.height * 0.7, { steps: 8 });
  await page.mouse.up();
  await expect(page.getByLabel('West longitude')).not.toHaveValue(previous);
  await expect(page.getByRole('button', { name: /Draw a rectangle/ })).toHaveAttribute('aria-pressed', 'false');
  await page.getByRole('button', { name: 'Gran Chaco', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { name: 'Sensor comparison' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/argentina-mobile.png', fullPage: true });
});

test('validation placeholder and entirely unavailable night window', async ({ page }) => {
  await page.route('**/api/validation', route => route.fulfill({ json: { status: 'pending', message: 'Awaiting out/validation.json', metrics: [] } }));
  await page.goto('/');
  await expect(page.getByText('Awaiting out/validation.json')).toBeVisible();
  await expect(page.locator('.validation-placeholder strong')).toHaveText(['—', '—']);
  await expect(page.getByLabel('End month')).toHaveValue('2024-12');
  await page.getByLabel('End month').fill('2011-12');
  await page.getByLabel('Day or night').selectOption('N');
  await page.getByRole('button', { name: 'Harmonized', exact: true }).click();
  await expect(page.locator('.calendar-scroll')).toContainText('Nighttime harmonized is unavailable before 2012');
  await expect(page.locator('.summary strong')).toHaveText('—');
  await expect(page.locator('.interval-band')).toHaveCount(0);
});
